#!/usr/bin/env python3
"""Quick look at a directory website for onboarding (free, no API keys, about 1 to 2 minutes).

    python3 site_scan.py https://example.com --out scan.json

Finds: what the site is built with (WordPress, Webflow, Wix, Squarespace, Next.js, Supabase, Airtable,
Brilliant Directories), how many pages the sitemap lists and how they group by URL pattern, which group
looks like listing pages and how many words those pages have (sample of 10), a blog, lead or contact
forms, ads, affiliate links, and broken links in a sample of up to 30 pages.

Prints and saves JSON. `plain_summary` is 3 to 6 short bullets you can show the owner as is.
If the site's security (Vercel or Cloudflare challenge, Sucuri, Wordfence, Akamai) answers instead of the page,
the result has `blocked_by_security: true`, `blocked_by` (vercel | cloudflare | other) and `next_step: use_web_reader`:
that is NOT a rate limit or an outage. Hermes reads the homepage, robots.txt, sitemap and ~5 pages with its own
built-in web reader instead (no owner action), and offers setup-guides/guides/let-hermes-past-security.md only
for jobs that read many pages (see `big_jobs`).
"""
import argparse
import collections
import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from html.parser import HTMLParser

UA = "Mozilla/5.0 (compatible; directory-ops/1.0; +https://github.com/Directoryops/directory-ops)"
FALLBACK_LINE = "Your site's security blocks simple scanners, so I used my web reader instead."
BIG_JOB_LINE = ("Your site's security blocks simple scanners. I can still check a small sample with my web reader, but for "
                "checking every page it's faster and cheaper to let me in (2 minutes). Want to do that now?")


def security_block(status, headers, body="", first=False):
    """'vercel' | 'cloudflare' | 'other' when a security wall answered instead of the page, else None."""
    h = {str(k).lower(): str(v).lower() for k, v in (headers or {}).items()}
    b = (body or "")[:6000].lower()
    server = h.get("server", "")
    if "x-vercel-challenge-token" in h or h.get("x-vercel-mitigated") == "challenge":
        return "vercel"
    if h.get("cf-mitigated") == "challenge" or ("cloudflare" in server and status in (403, 429, 503) and any(
            m in b for m in ("just a moment", "attention required", "challenge-platform", "cf-chl", "cf_chl"))):
        return "cloudflare"
    if "x-sucuri-id" in h or "x-sucuri-block" in h or "sucuri website firewall" in b or "access denied - sucuri" in b:
        return "other"
    if status in (403, 503) and ("wordfence" in b or "generated by wordfence" in b):
        return "other"
    if status == 403 and ("akamaighost" in server or "reference #" in b and "access denied" in b):
        return "other"
    if first and status == 429:
        return "other"
    return None
SKIP = re.compile(r"\.(jpg|jpeg|png|gif|webp|svg|pdf|zip|mp4|css|js|ico|xml|txt|json|woff2?)(\?|$)", re.I)
DEADLINE = 110  # seconds


def fetch_full(url, limit=1_500_000):
    """(status, final url, body, headers)."""
    try:
        parts = urllib.parse.urlsplit(url)
        url = urllib.parse.urlunsplit(parts._replace(path=urllib.parse.quote(parts.path, safe="/%:@!$&'()*+,;=-._~")))
        r = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=20)
        return r.status, r.geturl(), r.read(limit).decode("utf-8", "ignore"), dict(r.headers)
    except urllib.error.HTTPError as e:
        try:
            body = e.read(20000).decode("utf-8", "ignore")
        except Exception:  # noqa: BLE001
            body = ""
        return e.code, url, body, dict(e.headers or {})
    except Exception:  # noqa: BLE001
        return 0, url, "", {}


def fetch(url, limit=1_500_000):
    st, final, body, headers = fetch_full(url, limit)
    if st != 200:
        body = ""
    return st, final, body


class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.links, self.scripts, self.text, self.skip, self.forms, self._form = [], [], [], 0, [], None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "noscript", "svg"):
            self.skip += 1
            if tag == "script" and a.get("src"):
                self.scripts.append(a["src"])
        if tag == "a" and a.get("href"):
            self.links.append(a["href"])
        if tag == "form":
            self._form = {"action": a.get("action", ""), "fields": []}
        if tag in ("input", "textarea", "select") and self._form is not None:
            self._form["fields"].append((a.get("type", "") + " " + a.get("name", "") + " " + a.get("id", "") +
                                         " " + a.get("placeholder", "")).lower())

    def handle_endtag(self, tag):
        if tag in ("script", "style", "noscript", "svg") and self.skip:
            self.skip -= 1
        if tag == "form" and self._form is not None:
            self.forms.append(self._form)
            self._form = None

    def handle_data(self, d):
        if not self.skip:
            self.text.append(d)


def parse(html):
    p = Page()
    try:
        p.feed(html)
    except Exception:  # noqa: BLE001
        pass
    return p


def words(p):
    return len(re.findall(r"[A-Za-z]{2,}", " ".join(p.text)))


def sitemap_urls(root, host):
    out, todo, seen = [], [root + "/sitemap.xml", root + "/sitemap_index.xml", root + "/wp-sitemap.xml"], set()
    _, _, robots = fetch(root + "/robots.txt", 200_000)
    todo += re.findall(r"(?im)^sitemap:\s*(\S+)", robots or "")
    while todo and len(seen) < 25:
        sm = todo.pop(0)
        if sm in seen:
            continue
        seen.add(sm)
        st, _, xml = fetch(sm, 5_000_000)
        if st != 200 or "<loc>" not in xml:
            continue
        locs = [l.strip() for l in re.findall(r"<loc>\s*([^<]+?)\s*</loc>", xml)]
        if "<sitemapindex" in xml:
            todo += locs
        else:
            out += [l for l in locs if urllib.parse.urlparse(l).netloc.replace("www.", "") == host]
    return list(dict.fromkeys(out))


def pattern(path):
    segs = [s for s in path.strip("/").split("/") if s]
    if not segs:
        return "/"
    return "/" + "/".join(segs[:1] + ["*"] * (len(segs) - 1)) if len(segs) > 1 else "/*"


def detect_platform(html, scripts, root):
    h = html.lower()
    host = re.escape(urllib.parse.urlparse(root).netloc.lower().replace("www.", ""))
    found = []
    # WordPress files served from THIS site (images from other sites' uploads don't count)
    if re.search(r'(src|href)="(https?://(www\.)?' + host + r')?/wp-(content|includes)/', h):
        found.append("WordPress")
    if "webflow" in h:
        found.append("Webflow")
    if "wix.com" in h or "wixstatic" in h:
        found.append("Wix")
    if "squarespace" in h:
        found.append("Squarespace")
    if "/_next/static/" in h or 'id="__next"' in h:
        found.append("Next.js")
    if "brilliantdirectories" in h or "brilliant directories" in h:
        found.append("Brilliant Directories")
    if "airtable" in h:
        found.append("Airtable")
    if "supabase.co" in h:
        found.append("Supabase")
    if "Supabase" not in found:
        for src in [s for s in scripts if "/_next/static/" in s or s.endswith(".js")][:6]:
            st, _, js = fetch(urllib.parse.urljoin(root + "/", src), 2_000_000)
            if st == 200 and "supabase.co" in js:
                found.append("Supabase")
                break
    if "WordPress" not in found:
        st, _, body = fetch(root + "/wp-json/", 200_000)
        if st == 200 and '"namespaces"' in body:
            found.append("WordPress")
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("site")
    ap.add_argument("--out", default="")
    a = ap.parse_args()
    t0 = time.time()
    site = a.site if a.site.startswith("http") else "https://" + a.site
    st, final, html, headers = fetch_full(site)
    blocked = security_block(st, headers, html, first=True)
    if blocked:
        root0 = "{0.scheme}://{0.netloc}".format(urllib.parse.urlparse(site))
        res = {"site": site, "reachable": False, "status": st, "blocked_by_security": True, "blocked_by": blocked,
               "next_step": "use_web_reader",
               "say_to_owner": FALLBACK_LINE,
               "web_reader_plan": [root0 + "/", root0 + "/robots.txt", root0 + "/sitemap.xml",
                                   "then about 5 sample pages from the sitemap (one per page type)"],
               "web_reader_note": ("Read these with your built-in web reading tool (no owner action, no question), then "
                                   "build the 3 to 5 'Here's what I found' bullets yourself from what you read."),
               "big_jobs": {"say": BIG_JOB_LINE, "guide": "setup-guides/guides/let-hermes-past-security.md",
                            "applies_to": ["broken-links-and-seo-errors crawl", "internal-links", "page-copy-refresh checks",
                                           "lead-routing find_emails on the owner's own site"]},
               "plain_summary": [FALLBACK_LINE]}
        out = json.dumps(res, indent=1)
        print(out)
        if a.out:
            open(a.out, "w").write(out)
        return 0
    if st != 200:
        html = ""
    if st != 200 or not html:
        res = {"site": site, "reachable": False, "status": st,
               "plain_summary": ["I couldn't open the website (it may not be live yet), so I'll skip the website checks."]}
        out = json.dumps(res, indent=1)
        print(out)
        if a.out:
            open(a.out, "w").write(out)
        return 0
    root = "{0.scheme}://{0.netloc}".format(urllib.parse.urlparse(final))
    host = urllib.parse.urlparse(root).netloc.replace("www.", "")
    home = parse(html)

    platform = detect_platform(html, home.scripts, root)
    urls = sitemap_urls(root, host)
    if not urls:  # no sitemap: use homepage links
        urls = list(dict.fromkeys(urllib.parse.urljoin(root + "/", l).split("#")[0] for l in home.links))
        urls = [u for u in urls if urllib.parse.urlparse(u).netloc.replace("www.", "") == host and not SKIP.search(u)]

    groups = collections.Counter(pattern(urllib.parse.urlparse(u).path) for u in urls)
    blog = any(re.search(r"/(blog|articles|guides|news|resources)(/|$)", urllib.parse.urlparse(u).path) for u in urls) or \
        any(re.search(r"/(blog|articles|guides)(/|$|\")", l) for l in home.links)
    # listing-like group: the deepest pattern with many pages (not blog)
    cand = [(pat.count("*"), n, pat) for pat, n in groups.items()
            if n >= 5 and not re.match(r"/(blog|articles|guides|news|tag|category|author|page)\b", pat)]
    cand.sort(reverse=True)
    listing_pat = cand[0][2] if cand else ""
    listing_urls = [u for u in urls if pattern(urllib.parse.urlparse(u).path) == listing_pat]

    sample = listing_urls[:: max(1, len(listing_urls) // 10)][:10]
    wc, forms, aff, ads, lead_links = [], [], set(), set(), set()
    checked, broken = set(), []
    pages_to_check = [root + "/"] + sample + [u for u in urls if u not in sample][:19]

    def look(p_html, url):
        p = parse(p_html)
        h = p_html.lower()
        for f in p.forms:
            fs = " ".join(f["fields"])
            if re.search(r"email|phone|tel", fs) and not re.search(r"search|newsletter", fs + f["action"].lower()) or "quote" in fs:
                forms.append(urllib.parse.urlparse(url).path or "/")
        for l in p.links:
            if re.search(r"(get|free|request)[-_ ]?(a[-_ ])?quotes?|/quote|/quiz|/contact|/request|/book", l, re.I):
                lead_links.add(l.split("?")[0])
            if re.search(r"amazon\.[a-z.]+/.*(tag=|/dp/)|amzn\.to|[?&](ref|aff|affiliate|tag)=|shareasale|impact\.com|awin|cj\.com", l, re.I):
                aff.add(urllib.parse.urlparse(l).netloc)
        for name, sig in (("Google AdSense", "adsbygoogle"), ("Mediavine", "mediavine"), ("Raptive", "adthrive"),
                          ("Raptive", "raptive"), ("Ezoic", "ezoic"), ("Journey", "journeymv")):
            if sig in h:
                ads.add(name)
        return p

    for u in pages_to_check:
        if time.time() - t0 > DEADLINE * 0.6:
            break
        stt, _, ph = fetch(u)
        checked.add(u)
        if stt == 200 and ph:
            p = look(ph, u)
            if u in sample:
                wc.append(words(p))

    # broken links: internal links from the sampled pages, up to 30 checks
    links = []
    for u in list(checked)[:8]:
        _, _, ph = fetch(u)
        for l in parse(ph).links:
            full = urllib.parse.urljoin(u, l).split("#")[0]
            if urllib.parse.urlparse(full).netloc.replace("www.", "") == host and not SKIP.search(full) and full not in checked:
                links.append(full)
    for l in list(dict.fromkeys(links))[:30]:
        if time.time() - t0 > DEADLINE:
            break
        stt, _, _ = fetch(l, 20_000)
        if stt in (404, 410):
            broken.append(urllib.parse.urlparse(l).path)

    avg = round(sum(wc) / len(wc)) if wc else None
    summary = []
    n = len(urls)
    if n:
        summary.append(f"About {n:,} pages" + (f", about {len(listing_urls):,} of them look like listing or location pages" if listing_urls else ""))
    if platform:
        summary.append("Built with " + " + ".join(dict.fromkeys(platform)))
    else:
        summary.append("I couldn't tell what it's built with from the outside (that's normal for custom sites)")
    if avg is not None:
        thin = "on the thin side" if avg < 300 else ("decent" if avg < 800 else "detailed")
        summary.append(f"Listing pages average about {avg} words ({thin})")
    summary.append("There's a blog" if blog else "No blog yet")
    quote_pages = sorted(l for l in lead_links if re.search(r"quote|quiz|request|book", l, re.I))
    if forms or quote_pages:
        summary.append("There's a quote or contact form, so leads are possible")
    if ads:
        summary.append("Ads running: " + ", ".join(sorted(ads)))
    if aff:
        summary.append("Affiliate links found")
    if broken:
        summary.append(f"{len(broken)} broken link{'s' if len(broken) != 1 else ''} in a quick sample")
    res = {
        "site": root, "reachable": True, "platform": list(dict.fromkeys(platform)), "sitemap_pages": n,
        "page_groups": dict(groups.most_common(8)), "listing_pattern": listing_pat, "listing_pages": len(listing_urls),
        "listing_avg_words": avg, "blog": blog, "forms_on": sorted(set(forms))[:5], "quote_or_contact_links": sorted(lead_links)[:5], "ads": sorted(ads),
        "affiliate_domains": sorted(aff)[:5], "broken_links_sample": broken[:10], "seconds": round(time.time() - t0),
        "plain_summary": summary[:6],
    }
    out = json.dumps(res, indent=1)
    print(out)
    if a.out:
        open(a.out, "w").write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
